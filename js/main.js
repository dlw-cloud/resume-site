    function createTabs(container, tabs, renderPanel) {
        const prefix = 'tab-' + Math.random().toString(36).slice(2, 8);
        container.innerHTML = `
            <div class="tabs-nav" role="tablist">
                ${tabs.map((tab, i) => `<button class="tab-btn" role="tab" id="${prefix}-btn-${i}" aria-selected="${i === 0}" aria-controls="${prefix}-panel-${i}" data-index="${i}">${tx(tab.label)}</button>`).join('')}
            </div>
            <div class="tabs-panels">
                ${tabs.map((tab, i) => `<div class="tab-panel" role="tabpanel" id="${prefix}-panel-${i}" aria-hidden="${i !== 0}" data-index="${i}">${renderPanel(tab)}</div>`).join('')}
            </div>
        `;
        const btns = container.querySelectorAll('.tab-btn');
        const panels = container.querySelectorAll('.tab-panel');
        function switchTab(index) {
            btns.forEach((btn, i) => {
                btn.setAttribute('aria-selected', String(i === index));
            });
            panels.forEach((panel, i) => {
                panel.setAttribute('aria-hidden', String(i !== index));
            });
        }
        btns.forEach((btn) => {
            btn.addEventListener('click', () => switchTab(Number(btn.dataset.index)));
        });
    }

